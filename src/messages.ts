export function createTranslator(
  locale: string,
  messageOverrides: Record<string, string> = {}
): Translate {
  const fallbackMessages = defaultMessages.en;
  const localeMessages = defaultMessages[locale] || fallbackMessages;
  const messages = { ...fallbackMessages, ...localeMessages, ...messageOverrides };

  return (key: string) => messages[key] || key;
}
